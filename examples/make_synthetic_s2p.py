"""Generate clearly-labelled SYNTHETIC demonstration data (not measurements).

Data come from the independent ABCD-cascade forward model (nrw.forward) with seeded
complex Gaussian noise (rms 1e-3). Output: data/synthetic/*.s2p, one .csv variant and
data/synthetic/manifest.json (thickness, geometry and description of every file, used by the
web application's "Load demo data" button).
"""
import json
from pathlib import Path

import numpy as np

from nrw.forward import SampleSpec
from nrw.geometry import Coax
from nrw.io import write_touchstone
from nrw.materials import Debye, Lorentz
from nrw.perturb import complex_gaussian

OUT = Path(__file__).resolve().parents[1] / "data" / "synthetic"
OUT.mkdir(parents=True, exist_ok=True)
f = np.linspace(2e9, 18e9, 801)
rng = np.random.default_rng(2026)
cases = {
    "synthetic_magnetic_composite_2mm": (
        Debye(6.0, 4.0, 5e9), Lorentz(1.0, 2.5, 4e9, 6e9), 2.0e-3,
        "Magnetodielectric composite (Debye eps, Lorentz mu), 2 mm: well-conditioned reference case"),
    "synthetic_lowloss_dielectric_10mm": (
        Debye(4.0, 0.2, 30e9), 1.0, 10.0e-3,
        "Low-loss dielectric, 10 mm, mu = 1: crosses half-wavelength points (use the NIST mu = 1 method)"),
    "synthetic_thick_dielectric_30mm_branchwrap": (
        Debye(10.0, 0.5, 30e9), 1.0, 30.0e-3,
        "Thick dielectric, 30 mm: beta L > pi already at 2 GHz, several phase wraps (branch m up to 6)"),
    "synthetic_lowloss_magnetic_20mm_halfwave": (
        4.0 - 0.004j, 1.5 - 0.003j, 20.0e-3,
        "Low-loss magnetic sample, 20 mm: simultaneous eps/mu ill-conditioned near beta L = k pi"),
    # second thickness of the SAME material (appended last so earlier files keep their noise draws)
    "synthetic_lowloss_magnetic_13mm_halfwave": (
        4.0 - 0.004j, 1.5 - 0.003j, 13.0e-3,
        "Same low-loss magnetic material, 13 mm: second sample for the two-thickness joint solution"),
}
PAIRS = {"synthetic_lowloss_magnetic_20mm_halfwave.s2p": "synthetic_lowloss_magnetic_13mm_halfwave.s2p",
         "synthetic_lowloss_magnetic_13mm_halfwave.s2p": "synthetic_lowloss_magnetic_20mm_halfwave.s2p"}
manifest = {}
for name, (eps, mu, L, desc) in cases.items():
    spec = SampleSpec(eps=eps, mu=mu, length_m=L, geometry=Coax())
    s = [complex_gaussian(x, 1e-3, rng) for x in spec.sparams(f)]
    write_touchstone(OUT / f"{name}.s2p", f, *s, comments=[
        "SYNTHETIC DEMONSTRATION DATA - generated by examples/make_synthetic_s2p.py (nrw.forward ABCD cascade)",
        f"eps model: {eps!r}", f"mu model: {mu!r}", f"length_m: {L}", "geometry: 7 mm coax (TEM)",
        "noise: circular complex Gaussian, rms 1e-3, seed 2026"])
    manifest[f"{name}.s2p"] = {"thickness_mm": L * 1e3, "geometry": "coax", "description": desc,
                               "eps_model": repr(eps), "mu_model": repr(mu), "synthetic": True}
    print("wrote", OUT / f"{name}.s2p")
    if name == "synthetic_magnetic_composite_2mm":
        # CSV variant in magnitude(dB)/phase(deg) form with the frequency in GHz
        rows = ["# SYNTHETIC DEMONSTRATION DATA (same model as the .s2p of the same name)",
                "Frequency (GHz),S11_dB,S11_phase_deg,S21_dB,S21_phase_deg,S12_dB,S12_phase_deg,S22_dB,S22_phase_deg"]
        for k in range(len(f)):
            vals = [f[k] / 1e9]
            for x in s:
                vals += [20 * np.log10(abs(x[k])), np.degrees(np.angle(x[k]))]
            rows.append(",".join(f"{v:.10g}" for v in vals))
        (OUT / f"{name}.csv").write_text("\n".join(rows) + "\n")
        manifest[f"{name}.csv"] = dict(manifest[f"{name}.s2p"], description=desc + " (CSV, dB/phase format)")
        print("wrote", OUT / f"{name}.csv")
for a, b in PAIRS.items():
    manifest[a]["pair_with"] = b  # same material, different thickness (two-thickness demo)
(OUT / "manifest.json").write_text(json.dumps(manifest, indent=2))
print("wrote", OUT / "manifest.json")
