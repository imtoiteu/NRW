# --------------------------------------------------------------------------------------
# Scenarios (measurement non-idealities)
# --------------------------------------------------------------------------------------
@dataclass
class Dataset:
    f: np.ndarray
    s11: np.ndarray
    s21: np.ndarray
    s12: np.ndarray
    s22: np.ndarray
    L_assumed: float
    eps_true: np.ndarray
    mu_true: np.ndarray
    info: dict = field(default_factory=dict)


def _sparams(case: Case, f, z_ref=1.0, offsets=(0.0, 0.0), fixture_alpha=0.0, eps_mu=None):
    eps, mu = case.truth(f) if eps_mu is None else eps_mu
    alpha = fixture_alpha * np.sqrt(f / 1e9)
    layers = []
    if offsets[0]:
        layers.append(Layer(offsets[0], 1.0, 1.0, alpha))
    layers.append(Layer(case.L, eps, mu))
    if offsets[1]:
        layers.append(Layer(offsets[1], 1.0, 1.0, alpha))
    return cascade_sparams(f, GEOM, layers, z_ref)


def make_dataset(case: Case, scenario: str, seed: int = 0) -> Dataset:
    rng = np.random.default_rng(seed)
    f = F_DEFAULT.copy()
    L_assumed = case.L
    info = {}
    if scenario == "coarse_grid":
        f = np.linspace(2e9, 18e9, 33)  # 0.5 GHz steps
    elif scenario == "high_start":
        f = np.linspace(8e9, 18e9, 251)
    elif scenario == "missing_freq":
        keep = rng.random(len(f)) > 0.3
        keep &= ~((f > 8e9) & (f < 10e9))  # 2 GHz hole
        keep[0] = keep[-1] = True
        f = f[keep]
    eps_t, mu_t = case.truth(f)
    kw = {}
    if scenario == "air_gap":
        # 10 um radial gaps at inner and outer conductor (quasi-static capacitor model)
        eps_eff, mu_eff = coax_air_gap_effective(eps_t, mu_t, GEOM, GEOM.inner_diameter_m + 20e-6,
                                                 GEOM.outer_diameter_m - 20e-6)
        kw["eps_mu"] = (eps_eff, mu_eff)
    if scenario == "holder_mismatch":
        kw["z_ref"] = 1.02  # 51 ohm holder measured with a 50 ohm calibration
    if scenario == "fixture_loss":
        kw["offsets"] = (5e-3, 5e-3)
        kw["fixture_alpha"] = 0.05  # Np/m at 1 GHz, ~sqrt(f); planes de-embedded as lossless below
    s = list(_sparams(case, f, **kw))
    if scenario == "fixture_loss":
        s = list(shift_reference_planes(f, *s, GEOM, -5e-3, -5e-3))  # lossless de-embedding
    if scenario in ("noise_1e-3", "noise_3e-3", "noise_1e-2"):
        sigma = {"noise_1e-3": 1e-3, "noise_3e-3": 3e-3, "noise_1e-2": 1e-2}[scenario]
        s = [complex_gaussian(x, sigma, rng) for x in s]
        info["sigma"] = sigma
    elif scenario == "mag_noise":
        s = [magnitude_noise(x, 0.005, rng) for x in s]
    elif scenario == "phase_noise":
        s = [phase_noise(x, np.deg2rad(0.5), rng) for x in s]
    elif scenario == "ref_plane_error":
        s = list(shift_reference_planes(f, *s, GEOM, 50e-6, 0.0))  # 50 um uncorrected at port 1
    elif scenario == "thickness_error":
        L_assumed = case.L * 1.01
    elif scenario in ("coarse_grid", "high_start", "missing_freq", "air_gap", "holder_mismatch",
                      "fixture_loss", "noise_free"):
        pass
    else:
        raise ValueError(scenario)
    return Dataset(f, s[0], s[1], s[2], s[3], L_assumed, eps_t, mu_t, info)


