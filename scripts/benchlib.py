def external_algorithms():
    """Adapters written by the open-source survey (research/adapters)."""
    try:
        from research.adapters import ADAPTERS, available
    except Exception:  # noqa: BLE001
        return {}
    out = {}
    for name in available():
        fn = ADAPTERS[name]

        def run(d, fn=fn):
            r = fn(d.f, d.s11, d.s21, d.s12, d.s22, d.L_assumed, {"kind": "coax"})
            mu = r.get("mu")
            eps_only = mu is None
            return {"eps": np.asarray(r["eps"], complex),
                    "mu": np.ones(len(d.f), complex) if eps_only else np.asarray(mu, complex),
                    "eps_only": eps_only}
        out[f"ext:{name}"] = run
    return out


# --------------------------------------------------------------------------------------
# Metrics
# --------------------------------------------------------------------------------------
def true_branch(d: Dataset):
    beta = GEOM.gamma(d.f, d.eps_true, d.mu_true).imag
    return np.floor((beta * d.L_assumed + np.pi) / (2 * np.pi)).astype(int)


def metrics(d: Dataset, out: dict, case: Case, fail_rel=0.10) -> dict:
    eps, mu = np.asarray(out["eps"], complex), np.asarray(out["mu"], complex)
    et, mt = d.eps_true, d.mu_true
    finite = np.isfinite(eps) & np.isfinite(mu)
    m = {}

    def rmse(a, b):
        e = a - b
        return float(np.sqrt(np.mean(e[finite] ** 2))) if finite.any() else np.nan

    m["rmse_eps_real"] = rmse(eps.real, et.real)
    m["rmse_eps_loss"] = rmse(-eps.imag, -et.imag)
    m["rmse_mu_real"] = rmse(mu.real, mt.real)
    m["rmse_mu_loss"] = rmse(-mu.imag, -mt.imag)
    rel_e = np.abs(eps - et) / np.abs(et)
    rel_m = np.abs(mu - mt) / np.abs(mt)
    m["median_rel_err_eps"] = float(np.nanmedian(np.where(finite, rel_e, np.nan))) if finite.any() else np.nan
    m["median_rel_err_mu"] = float(np.nanmedian(np.where(finite, rel_m, np.nan))) if finite.any() else np.nan
    m["max_abs_err_eps"] = float(np.nanmax(np.where(finite, np.abs(eps - et), np.nan))) if finite.any() else np.nan
    m["max_abs_err_mu"] = float(np.nanmax(np.where(finite, np.abs(mu - mt), np.nan))) if finite.any() else np.nan
    fail = ~finite | (rel_e > fail_rel) | (rel_m > fail_rel)
    m["failure_rate"] = float(np.mean(fail))
    m["nonfinite_count"] = int(np.count_nonzero(~finite))
    m["passivity_violations_raw"] = int(np.count_nonzero((eps.imag > 0) | (mu.imag > 0)))
    # significant violation: negative loss beyond 3x the Cramer-Rao std at the scenario noise
    from nrw.conditioning import crlb
    sig = d.info.get("sigma", 1e-3)
    std, _ = crlb(d.f, GEOM, et, mt, d.L_assumed, sig, params="eps" if out.get("eps_only") else "eps_mu")
    se = 3 * std[:, 1]
    sm = 3 * std[:, 3] if std.shape[1] == 4 else np.full(len(d.f), np.inf)
    m["passivity_violations"] = int(np.count_nonzero((-eps.imag < -se) | (-mu.imag < -sm)))
    m["unphysical_count"] = int(np.count_nonzero(~finite | (np.abs(eps) > 1e4) | (np.abs(mu) > 1e4)
                                                 | (-eps.imag < -se) | (-mu.imag < -sm)))
    if "branch" in out and out["branch"] is not None:
        b = np.asarray(out["branch"])
        m["branch_discontinuities"] = int(np.count_nonzero(np.diff(b) != 0))
        m["branch_error_rate"] = float(np.mean(b != true_branch(d)))
    else:
        m["branch_discontinuities"] = np.nan
        m["branch_error_rate"] = np.nan
    m["mu_assumed_1"] = bool(out.get("eps_only", False))
    m["assumption_violated"] = bool(out.get("eps_only", False) and case.magnetic)
    return m


def run_one(alg_name, fn, case: Case, scenario: str, seed: int):
    d = make_dataset(case, scenario, seed)
    t0 = time.perf_counter()
    try:
        with np.errstate(all="ignore"):
            out = fn(d)
        err = ""
    except Exception as e:  # noqa: BLE001 - recorded, not hidden
        out = {"eps": np.full(len(d.f), np.nan + 0j), "mu": np.full(len(d.f), np.nan + 0j)}
        err = f"{type(e).__name__}: {e}"[:300]
        if "--debug" in sys.argv:
            traceback.print_exc()
    dt = time.perf_counter() - t0
    row = {"algorithm": alg_name, "case": case.name, "scenario": scenario, "seed": seed,
           "n_freq": len(d.f), "runtime_s": dt, "error": err}
    row.update(metrics(d, out, case))
    return row, d, out
