# --------------------------------------------------------------------------------------
# Algorithms (internal)
# --------------------------------------------------------------------------------------
def _nrw_branch(d: Dataset, method):
    s11 = (d.s11 + d.s22) / 2
    s21 = (d.s21 + d.s12) / 2
    base = nrw(d.f, s11, s21, d.L_assumed, GEOM)
    b = select_branch(method, d.f, base.transmission, d.L_assumed, GEOM)
    return nrw(d.f, s11, s21, d.L_assumed, GEOM, branch=b.m), b


def alg_nrw(branch_method):
    def run(d):
        r, b = _nrw_branch(d, branch_method)
        return {"eps": r.eps, "mu": r.mu, "branch": b.m}
    return run


def alg_nrw_eps(d):
    r, b = _nrw_branch(d, "anchored")
    return {"eps": r.eps_mu_only, "mu": np.ones(len(d.f), complex), "branch": b.m, "eps_only": True}


def alg_bj(d):
    r, b = _nrw_branch(d, "anchored")
    it = solve_eps_only(d.f, d.s11, d.s21, d.L_assumed, GEOM, r.eps_mu_only, s12=d.s12, s22=d.s22,
                        formulation="eq2.24+2.25")
    return {"eps": it.eps, "mu": it.mu, "branch": b.m, "eps_only": True, "converged": it.converged}


def alg_iter(d):
    r, b = _nrw_branch(d, "anchored")
    it = solve_eps_mu_pointwise(d.f, d.s11, d.s21, d.L_assumed, GEOM, r.eps, r.mu, s12=d.s12, s22=d.s22,
                                multistart=False)
    return {"eps": it.eps, "mu": it.mu, "branch": b.m, "converged": it.converged}


def alg_reg(d, lam=1.0):
    r, b = _nrw_branch(d, "anchored")
    it = solve_eps_mu_pointwise(d.f, d.s11, d.s21, d.L_assumed, GEOM, r.eps, r.mu, s12=d.s12, s22=d.s22,
                                multistart=False)
    e0 = np.where(np.isfinite(it.eps), it.eps, r.eps)
    u0 = np.where(np.isfinite(it.mu), it.mu, r.mu)
    sigma = d.info.get("sigma", 1e-3)
    rg = solve_eps_mu_regularized(d.f, d.s11, d.s21, d.L_assumed, GEOM, e0, u0, s12=d.s12, s22=d.s22,
                                  lam=lam, sigma=sigma)
    return {"eps": rg.eps, "mu": rg.mu, "branch": b.m}


